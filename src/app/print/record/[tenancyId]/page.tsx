import { notFound } from "next/navigation";
import { PrintButton } from "@/components/shared/print-button";
import { Logo } from "@/components/brand/logo";
import { formatDate, formatDateTime } from "@/lib/dates";
import { AppError } from "@/lib/errors";
import { label } from "@/lib/nigeria";
import { requirePageActor } from "@/server/auth/current";
import { connectDb } from "@/server/db";
import { TimelineEvent } from "@/server/models";
import { getTenancyForActor } from "@/server/services/access";

export const metadata = { title: "Tenancy record" };

/** Full, chronological, printable Shared Tenancy Record. */
export default async function PrintRecordPage({ params }: { params: Promise<{ tenancyId: string }> }) {
  const actor = await requirePageActor("landlord", "tenant");
  const { tenancyId } = await params;
  const t = await getTenancyForActor(actor, tenancyId).catch((e) => {
    if (e instanceof AppError && e.code === "NOT_FOUND") notFound();
    throw e;
  });
  await connectDb();
  const filter: Record<string, unknown> = { tenancyId: t._id };
  if (actor.role !== "landlord") filter.visibility = "shared";
  const events = await TimelineEvent.find(filter).sort({ occurredAt: 1, _id: 1 }).limit(5000).populate<{ actorId: { name: string } | null }>("actorId", "name").lean();
  return (
    <div className="space-y-4">
      <div className="no-print flex justify-end"><PrintButton /></div>
      <article className="print-card rounded-3xl border border-cream-300 bg-white p-6 sm:p-10">
        <Logo size="sm" />
        <h1 className="mt-1 text-2xl font-semibold">Shared tenancy record</h1>
        <p className="mt-1 text-sm text-ink-600">{t.tenantName} · {formatDate(t.startDate)} – {formatDate(t.endDate)} · {events.length} entries · generated {formatDateTime(new Date())} WAT</p>
        <table className="mt-6 w-full text-sm">
          <thead><tr className="border-b border-cream-200 text-left text-xs uppercase tracking-wide text-ink-500"><th className="py-2 pr-3 font-medium">When (WAT)</th><th className="py-2 pr-3 font-medium">Event</th><th className="py-2 pr-3 font-medium">Source</th><th className="py-2 font-medium">By</th></tr></thead>
          <tbody>
            {events.map((e) => (
              <tr key={e._id.toString()} className="border-b border-cream-100 align-top">
                <td className="whitespace-nowrap py-2 pr-3 text-xs">{formatDateTime(e.occurredAt)}</td>
                <td className="py-2 pr-3"><span className="font-medium">{label(e.type)}</span><span className="block text-ink-700">{e.summary}</span></td>
                <td className="py-2 pr-3 text-xs">{label(e.source)}</td>
                <td className="py-2 text-xs">{e.actorId?.name ?? "System"}</td>
              </tr>
            ))}
          </tbody>
        </table>
        <p className="mt-6 text-xs text-ink-500">Timestamps are generated by the server. Each entry shows whether it was submitted by the tenant, recorded or confirmed by the landlord, confirmed by the payment provider, or generated by the system. This record does not by itself establish legal liability or the authenticity of uploaded documents.</p>
      </article>
    </div>
  );
}
